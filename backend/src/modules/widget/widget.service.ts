import { prisma } from '../../server';
import crypto from 'crypto';

export class WidgetService {

    // ─── CRUD ─────────────────────────────────────────────

    static async list() {
        return prisma.webWidget.findMany({ orderBy: { createdAt: 'desc' } });
    }

    static async create(data: {
        name: string;
        allowedOrigin?: string;
        primaryColor?: string;
        welcomeMessage?: string;
        agentName?: string;
        tenantId: string;
    }) {
        const widgetToken = crypto.randomBytes(24).toString('hex');
        return prisma.webWidget.create({
            data: {
                name: data.name,
                widgetToken,
                allowedOrigin: data.allowedOrigin || '*',
                primaryColor: data.primaryColor || '#6366f1',
                welcomeMessage: data.welcomeMessage || 'Olá! 👋 Como podemos ajudar?',
                agentName: data.agentName || 'Atendimento',
                tenantId: data.tenantId,
            },
        });
    }

    static async update(id: string, data: {
        name?: string;
        allowedOrigin?: string;
        primaryColor?: string;
        welcomeMessage?: string;
        agentName?: string;
        isActive?: boolean;
    }) {
        return prisma.webWidget.update({ where: { id }, data });
    }

    static async delete(id: string) {
        await prisma.webWidgetSession.deleteMany({ where: { widgetId: id } });
        return prisma.webWidget.delete({ where: { id } });
    }

    static async findByToken(token: string) {
        return prisma.webWidget.findUnique({ where: { widgetToken: token } });
    }

    // ─── Session Management ────────────────────────────────

    /**
     * Find or create a session for a visitor.
     * visitorId: a UUID generated by the widget SDK on first visit, stored in localStorage.
     * Returns { session, ticket, isNew }
     */
    static async findOrCreateSession(widgetId: string, visitorId: string, visitorName?: string) {
        const widget = await prisma.webWidget.findUnique({ where: { id: widgetId } });
        if (!widget || !widget.isActive) throw new Error('Widget inativo ou não encontrado');

        let session = await prisma.webWidgetSession.findFirst({
            where: { widgetId, visitorId },
            include: { contact: true },
        });

        let contact: any;
        let isNew = false;

        if (session) {
            contact = session.contact;
        } else {
            // Create contact for this visitor (per-tenant compound unique on phone)
            const existingContact = await prisma.contact.findFirst({
                where: { phone: `widget_${visitorId}`, tenantId: widget.tenantId },
            });
            contact = existingContact || await prisma.contact.create({
                data: {
                    phone: `widget_${visitorId}`,
                    name: visitorName || 'Visitante',
                    channel: 'web_widget',
                    tenantId: widget.tenantId,
                },
            });

            session = await prisma.webWidgetSession.create({
                data: {
                    widgetId,
                    visitorId,
                    contactId: contact.id,
                    visitorName: visitorName || 'Visitante',
                },
                include: { contact: true },
            });
            isNew = true;
        }

        // Find or create an active ticket for this session
        const { TicketsService } = await import('../tickets/tickets.service');
        const { ticket } = await TicketsService.findOrCreateByContact(contact.phone, contact.name || 'Visitante');

        return { session: session!, ticket: ticket!, contact, isNew };
    }

    /**
     * Identify a visitor with CRM data (CPF/email) — triggers auto-merge if applicable.
     */
    static async identifyVisitor(sessionId: string, data: { fullName?: string; cpf?: string; email?: string }) {
        const session = await prisma.webWidgetSession.findUnique({
            where: { id: sessionId },
            include: { contact: true },
        });
        if (!session) throw new Error('Sessão não encontrada');

        const { ContactsService } = await import('../contacts/contacts.service');
        const updated = await ContactsService.update(session.contactId!, data);

        // Auto-merge if CPF matches a known contact
        if (data.cpf) {
            const cleaned = data.cpf.replace(/\D/g, '');
            ContactsService.autoMergeByCpf(session.contactId!, cleaned).catch(e =>
                console.warn('[Widget AutoMerge]', e.message)
            );
        }

        return updated;
    }

    /**
     * Get all messages in a session (by ticket).
     */
    static async getSessionMessages(ticketId: string) {
        return prisma.message.findMany({
            where: { ticketId },
            orderBy: { createdAt: 'asc' },
            include: { user: { select: { id: true, name: true } } },
        });
    }
}
