/** Monta o HTML do e-mail de recuperação de senha (exportado para preview/teste). */
export function buildPasswordResetEmailHtml(resetUrl: string): string {
  const content = `
    <h1 style="color:${C.title};margin:0 0 10px;font-size:20px;font-weight:700;">Recuperação de senha</h1>
    <p style="color:${C.text};margin:0 0 8px;font-size:14px;line-height:1.6;">
      Recebemos uma solicitação para redefinir a senha da sua conta no Atende Mafra.
      Clique no botão abaixo para criar uma nova senha.
    </p>

    <div style="text-align:center;margin:28px 0;">${ctaButton(resetUrl, 'Redefinir senha')}</div>

    <p style="color:${C.muted};font-size:13px;line-height:1.6;margin:0;">
      Este link expira em 1 hora. Se você não solicitou a redefinição, ignore este e-mail — sua senha permanece a mesma.
    </p>
  `;

  return renderEmailShell({ title: 'Recuperação de senha — Atende Mafra', contentHtml: content });
}

export async function sendEmail(
  to: string,
  subject: string,
  html: string,
  attachments?: { filename: string; path: string; cid: string }[]
) {
  const from = process.env.SMTP_FROM
    || (process.env.SMTP_USER ? `Atende Mafra <${process.env.SMTP_USER}>` : 'Atende Mafra <noreply@atendemafra.gov.br>');
  const info = await transporter.sendMail({ from, to, subject, html, attachments });
  console.log('Email enviado:', info.messageId);
  return info;
}

export async function sendPasswordResetEmail(to: string, token: string) {
  const resetUrl = `${process.env.FRONTEND_URL}/reset-password?token=${token}`;
  const html = buildPasswordResetEmailHtml(resetUrl);
  return sendEmail(to, 'Recuperação de senha — Atende Mafra', html, logoAttachments());
}

export async function sendWelcomeEmail(
  to: string,
  name: string,
  password: string,
  wasAutoGenerated: boolean
) {
  const html = buildWelcomeEmailHtml(to, name, password, wasAutoGenerated);
  return sendEmail(to, `Bem-vindo ao Atende Mafra, ${name}`, html, logoAttachments());
}
