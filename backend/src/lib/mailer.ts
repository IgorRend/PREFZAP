import nodemailer from 'nodemailer';
import fs from 'fs';
import path from 'path';

const transporter = nodemailer.createTransport({
  host: process.env.SMTP_HOST || 'smtp.gmail.com',
  port: parseInt(process.env.SMTP_PORT || '587'),
  secure: false,
  auth: {
    user: process.env.SMTP_USER,
    pass: process.env.SMTP_PASS,
  },
});

// ── Brasão de Mafra (embutido via CID) ─────────────────────────────
// Resolve para backend/assets tanto em dev (src/lib) quanto em build (dist/lib).
// Enviar como anexo inline garante que a imagem apareça mesmo com bloqueio de
// imagens externas (Gmail/Outlook) e sem depender de um host público.
const LOGO_PATH = path.resolve(__dirname, '../../assets/brasao.png');
const LOGO_EXISTS = fs.existsSync(LOGO_PATH);
const LOGO_CID = 'brasao';

function logoAttachments(): { filename: string; path: string; cid: string }[] {
  return LOGO_EXISTS ? [{ filename: 'brasao.png', path: LOGO_PATH, cid: LOGO_CID }] : [];
}

